package com.resumeiqai.service;

import com.lowagie.text.Document;
import com.lowagie.text.Font;
import com.lowagie.text.Paragraph;
import com.lowagie.text.pdf.PdfWriter;

import java.awt.*;
import java.io.FileOutputStream;

public class PDFReportGenerator {

    public void generateReport(String report, String filePath) {

        try {

            Document document = new Document();

            PdfWriter.getInstance(document, new FileOutputStream(filePath));

            document.open();

            Font titleFont = new Font(Font.HELVETICA, 22, Font.BOLD);
            Font headingFont = new Font(Font.HELVETICA, 16, Font.BOLD);
            Font bodyFont = new Font(Font.HELVETICA, 12);

            Paragraph title = new Paragraph("ResumeIQ AI Analysis Report", titleFont);
            title.setAlignment(Paragraph.ALIGN_CENTER);

            document.add(title);

            document.add(new Paragraph(" "));
            document.add(new Paragraph("Generated by ResumeIQ AI", bodyFont));
            document.add(new Paragraph(" "));
            document.add(new Paragraph("---------------------------------------------"));

            String[] lines = report.split("\n");

            for (String line : lines) {

                if (line.contains("Resume Score")
                        || line.contains("Skills Found")
                        || line.contains("Missing Skills")
                        || line.contains("Recommended Job Roles")
                        || line.contains("Suggestions")) {

                    document.add(new Paragraph(" "));
                    document.add(new Paragraph(line, headingFont));

                } else {

                    document.add(new Paragraph(line, bodyFont));

                }

            }

            document.close();

        }

        catch (Exception e) {

            e.printStackTrace();

        }

    }

}